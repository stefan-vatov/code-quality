import { RuleTester } from 'oxlint/plugins-dev';

import { requireDisableJustificationRule } from '../../src/rules/internal/require-disable-justification';

const tester = new RuleTester({ languageOptions: { parserOptions: { lang: 'ts' } } });
const missing = { messageId: 'missingJustification' };
const weak = { messageId: 'weakJustification' };
const protectedRule = { messageId: 'protectedRule' };

tester.run('thethracian/require-disable-justification', requireDisableJustificationRule, {
  valid: [
    'const value = 1;',
    '// a normal comment that mentions oxlint-disable in prose\nconst value = 1;',
    '// oxlint-disable-next-line no-debugger -- the debugger pause is intentional here\ndebugger;',
    '/* eslint-disable no-alert -- legacy alert flow kept for parity */\nalert(1);',
    '/* oxlint-disable no-alert -- legacy alert flow kept for parity */\n/* oxlint-enable no-alert */',
    'console.log(1); // eslint-disable-line no-console -- CLI prints progress to stdout',
    '// oxlint-disable-next-line no-explicit-any -- TODO: the SDK types this payload as any until v3 ships\nconst value: any = 1;',
  ],
  invalid: [
    {
      name: 'next-line directive without a reason',
      code: '// oxlint-disable-next-line no-debugger\ndebugger;',
      errors: [missing],
    },
    {
      name: 'eslint-prefixed line directive without a reason',
      code: 'console.log(1); // eslint-disable-line no-console',
      errors: [missing],
    },
    {
      name: 'block directive without a reason',
      code: '/* oxlint-disable no-alert */\nalert(1);',
      errors: [missing],
    },
    {
      name: 'separator with an empty reason',
      code: 'console.log(1); // oxlint-disable-line no-console --   ',
      errors: [missing],
    },
    {
      name: 'reason shorter than four words',
      code: '// oxlint-disable-next-line no-debugger -- intentional pause\ndebugger;',
      errors: [weak],
    },
    {
      name: 'boilerplate reason',
      code: '// oxlint-disable-next-line no-debugger -- this is a false positive\ndebugger;',
      errors: [weak],
    },
    {
      name: 'deferred-fix boilerplate',
      code: '// oxlint-disable-next-line no-debugger -- will fix this properly later\ndebugger;',
      errors: [weak],
    },
    {
      name: 'reason that only restates the rule name',
      code: '// oxlint-disable-next-line no-debugger -- no-debugger no debugger rule\ndebugger;',
      errors: [weak],
    },
    {
      name: 'disabling the justification rule itself',
      code: '// oxlint-disable-next-line thethracian/require-disable-justification -- the next directive is generated by a tool\n// oxlint-disable-next-line no-debugger\ndebugger;',
      errors: [protectedRule, missing],
    },
    {
      name: 'disabling the blanket-disable rule',
      code: '// eslint-disable-next-line unicorn/no-abusive-eslint-disable -- generated header from the router tool\n/* eslint-disable */',
      errors: [protectedRule, missing],
    },
  ],
});
